const {test}=require('node:test');
const assert=require('node:assert/strict');
const {spawn}=require('node:child_process');
const fs=require('node:fs');const os=require('node:os');const path=require('node:path');
test('parcours public et administration sécurisée',async t=>{
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'bellagio-'));
const child=spawn(process.execPath,['server.js'],{env:{...process.env,PORT:'3099',DATA_DIR:dir,ADMIN_PASSWORD:'test-secret-only'}});
t.after(()=>{child.kill();fs.rmSync(dir,{recursive:true,force:true})});
await new Promise((resolve,reject)=>{child.stdout.once('data',resolve);child.once('error',reject);child.once('exit',()=>reject(Error('Server stopped')))});
const req=(url,method='GET',body,cookie)=>fetch('http://127.0.0.1:3099'+url,{method,headers:{'Content-Type':'application/json',...(cookie?{cookie}:{})},...(body?{body:JSON.stringify(body)}:{})});
assert.equal((await req('/')).status,200);assert.equal((await req('/admin')).status,200);
const content=await(await req('/api/content')).json();assert.equal(content.requests,undefined);
assert.equal((await req('/api/admin')).status,401);
assert.equal((await req('/api/login','POST',{password:'incorrect'})).status,401);
assert.equal((await req('/api/requests','POST',{name:'x'})).status,400);
assert.equal((await req('/api/requests','POST',{name:'Test visite',phone:'+216 52 000 000',date:'2027-12-20',space:'La Volta',event:'Mariage',guests:200,message:'Demande test'})).status,201);
const login=await req('/api/login','POST',{password:'test-secret-only'});assert.equal(login.status,200);
const token=(await login.json()).token;assert.ok(token);
const bearer=await fetch('http://127.0.0.1:3099/api/admin',{headers:{Authorization:'Bearer '+token}});assert.equal(bearer.status,200);
const cookie=login.headers.get('set-cookie').split(';')[0];assert.match(login.headers.get('set-cookie'),/HttpOnly/);
const admin=await(await req('/api/admin','GET',null,cookie)).json();assert.equal(admin.requests.length,1);
assert.equal((await req('/api/admin/requests/'+admin.requests[0].id,'PATCH',{status:'Confirmée'},cookie)).status,200);
assert.equal((await req('/api/admin/requests/'+admin.requests[0].id,'PATCH',{status:'Invalid'},cookie)).status,400);
assert.equal((await req('/api/admin/content','PATCH',{title:'Un nouveau titre'},cookie)).status,200);
assert.equal((await(await req('/api/content')).json()).title,'Un nouveau titre');
assert.equal((await req('/api/logout','POST',{},cookie)).status,200);
assert.equal((await req('/api/admin','GET',null,cookie)).status,401);
assert.equal((await fetch('http://127.0.0.1:3099/api/admin',{headers:{Authorization:'Bearer '+token}})).status,401);
});
